type ResponseReceiver = mpsc::Receiver<FileContentsResponse<'static>>;

/// What a range request brought, or will.
#[derive(Debug)]
enum ChunkData {
    Pending(ResponseReceiver),
    Ready(Vec<u8>),
}

/// One `RANGE` request: `len` bytes from `start`.
#[derive(Debug)]
struct Chunk {
    start: u64,
    len: u32,
    data: ChunkData,
}

impl Chunk {
    fn end(&self) -> u64 {
        self.start.saturating_add(u64::from(self.len))
    }
}

#[derive(Debug)]
struct StreamState {
    position: u64,
    size: Option<u64>,
    /// Requests in flight, or answered and not read yet, back to back from the first one.
    chunks: VecDeque<Chunk>,
    /// Bytes asked per request; drops to what the remote serves when it serves less.
    chunk_len: u32,
}

/// Read-only stream over one remote file, `lindex` in the remote file list.
///
/// Reads are served from requests sent ahead of the reader, [`PIPELINE_DEPTH`] at a time, so
/// that the remote always has the next chunk to send. Responses come straight from the
/// `CLIPRDR` backend through [`ClipboardShared`], so the stream works on any thread.
#[implement(IStream, Agile = false)]
struct RemoteFileStream {
    shared: Arc<ClipboardShared>,
    file_list: Arc<RemoteFileList>,
    lindex: i32,
    state: Mutex<StreamState>,
}

impl RemoteFileStream {
    fn new(shared: Arc<ClipboardShared>, file_list: Arc<RemoteFileList>, lindex: i32, size: Option<u64>) -> Self {
        Self {
            shared,
            file_list,
            lindex,
            state: Mutex::new(StreamState {
                position: 0,
                size,
                chunks: VecDeque::new(),
                chunk_len: MAX_FILE_CONTENTS_CHUNK,
            }),
        }
    }

    fn lock_state(&self) -> MutexGuard<'_, StreamState> {
        self.state.lock().unwrap_or_else(PoisonError::into_inner)
    }

    fn descriptor(&self) -> Option<&FileDescriptor> {
        usize::try_from(self.lindex)
            .ok()
            .and_then(|index| self.file_list.files.get(index))
    }

    /// Whether `Cliprdr` still accepts requests against this stream's file list.
    ///
    /// Requests carry the `clipDataId` of the lock taken with the list, which keeps them valid
    /// across remote clipboard changes until `Cliprdr` releases it. Without a lock, they are
    /// checked against the current remote clipboard, so they only make sense until it changes.
    fn can_request(&self) -> bool {
        if self.shared.session() != self.file_list.session {
            return false;
        }

        match self.file_list.clip_data_id {
            Some(clip_data_id) => !self.shared.is_lock_released(clip_data_id),
            None => self.shared.generation() == self.file_list.generation,
        }
    }

    /// Sends a request, returning where its response will arrive.
    fn request(
        &self,
        flags: FileContentsFlags,
        position: u64,
        requested_size: u32,
    ) -> Result<ResponseReceiver, HRESULT> {
        if !self.can_request() {
            debug!(lindex = self.lindex, "Remote file is no longer available");
            return Err(STG_E_READFAULT);
        }

        let huge_file_support = self
            .shared
            .capabilities()
            .contains(ClipboardGeneralCapabilityFlags::HUGE_FILE_SUPPORT_ENABLED);
        if !huge_file_support && HUGE_FILE_POSITION <= position {
            debug!(
                lindex = self.lindex,
                position, "Remote file position needs huge file support"
            );
            return Err(STG_E_READFAULT);
        }

        Ok(self.shared.request_file_contents(FileContentsRequest {
            // Assigned by `ClipboardShared`.
            stream_id: 0,
            index: self.lindex,
            flags,
            position,
            requested_size,
            data_id: self.file_list.clip_data_id,
        }))
    }

    fn receive(&self, receiver: &ResponseReceiver, position: u64) -> Result<Vec<u8>, HRESULT> {
        match receiver.recv_timeout(RESPONSE_TIMEOUT) {
            Ok(response) if !response.is_error() => Ok(response.data().to_vec()),
            Ok(_) => {
                warn!(lindex = self.lindex, position, "The remote failed to read the file");
                Err(STG_E_READFAULT)
            }
            Err(error) => {
                warn!(%error, lindex = self.lindex, position, "No file contents from the remote");
                Err(STG_E_READFAULT)
            }
        }
    }

    fn size(&self) -> Result<u64, HRESULT> {
        if let Some(size) = self.lock_state().size {
            return Ok(size);
        }

        let receiver = self.request(FileContentsFlags::SIZE, 0, 8)?;
        let data = self.receive(&receiver, 0)?;
        let size = <[u8; 8]>::try_from(data.as_slice())
            .map(u64::from_le_bytes)
            .map_err(|_| STG_E_READFAULT)?;

        self.lock_state().size = Some(size);
        Ok(size)
    }

    /// Requests the chunks following the last one, up to the pipeline depth or the end of the
    /// file. Without a known size, the end is only found by reading it, so one at a time.
    fn fill_pipeline(&self, state: &mut StreamState) -> Result<(), HRESULT> {
        let depth = if state.size.is_some() { PIPELINE_DEPTH } else { 1 };

        while state.chunks.len() < depth {
            let start = state.chunks.back().map_or(state.position, Chunk::end);
            let len = range_request_len(start, state.size, state.chunk_len);
            if len == 0 {
                break;
            }

            let receiver = self.request(FileContentsFlags::RANGE, start, len)?;
            state.chunks.push_back(Chunk {
                start,
                len,
                data: ChunkData::Pending(receiver),
            });
        }

        Ok(())
    }

    /// Waits for the first chunk's data, shrinking the chunk to what the remote sent.
    ///
    /// Returns `false` at the end of a file whose size wasn't advertised.
    fn receive_front(&self, state: &mut StreamState) -> Result<bool, HRESULT> {
        let Some(chunk) = state.chunks.front_mut() else {
            return Ok(false);
        };

        let ChunkData::Pending(receiver) = &chunk.data else {
            return Ok(true);
        };

        let mut data = self.receive(receiver, chunk.start)?;
        data.truncate(usize::try_from(chunk.len).unwrap_or(usize::MAX));
        let served = u32::try_from(data.len()).unwrap_or(u32::MAX);
        let start = chunk.start;
        let requested = chunk.len;
        chunk.len = served;
        chunk.data = ChunkData::Ready(data);

        if served == requested {
            return Ok(true);
        }

        if served == 0 {
            if state.size.is_none() {
                return Ok(false);
            }

            warn!(
                lindex = self.lindex,
                position = start,
                "The remote sent no data before the end of the file"
            );
            return Err(STG_E_READFAULT);
        }

        // The remote serves less than asked: the requests after this one would leave a gap,
        // and the next ones ask for what it serves.
        trace!(lindex = self.lindex, served, requested, "Short remote file read");
        state.chunk_len = served;
        state.chunks.truncate(1);
        Ok(true)
    }

    /// Fills `out` from the current position, returning the byte count and the failure that
    /// stopped it, if any. Without a failure, fewer bytes than `out` holds means end of file.
    fn read_into(&self, out: &mut [u8]) -> (usize, Option<HRESULT>) {
        let mut state = self.lock_state();
        let mut filled = 0;

        while filled < out.len() {
            let position = state.position;

            let covered = state
                .chunks
                .front()
                .is_some_and(|chunk| chunk.start <= position && position < chunk.end());
            if !covered {
                // First read, or after a seek: the requests start over from the position.
                state.chunks.clear();
            }

            if let Err(error) = self.fill_pipeline(&mut state) {
                // What was already requested can still be read.
                if state.chunks.is_empty() {
                    return (filled, Some(error));
                }
            }

            match self.receive_front(&mut state) {
                Ok(true) => {}
                Ok(false) => break,
                Err(error) => {
                    // A later read asks again.
                    state.chunks.clear();
                    return (filled, Some(error));
                }
            }

            let Some(chunk) = state.chunks.front() else {
                break;
            };
            let ChunkData::Ready(data) = &chunk.data else {
                break;
            };

            // A short read may have left `position` past the chunk: it is then filled anew.
            let offset = position.saturating_sub(chunk.start);
            let available = usize::try_from(offset)
                .ok()
                .and_then(|offset| data.get(offset..))
                .unwrap_or(&[]);
            let count = available.len().min(out.len() - filled);
            out[filled..filled + count].copy_from_slice(&available[..count]);
            filled += count;

            let chunk_end = chunk.end();
            state.position = position.saturating_add(u64::try_from(count).unwrap_or(u64::MAX));
            if chunk_end <= state.position {
                state.chunks.pop_front();
            }
        }

        (filled, None)
    }
}

impl ISequentialStream_Impl for RemoteFileStream_Impl {
    fn Read(&self, pv: *mut c_void, cb: u32, pcbread: *mut u32) -> HRESULT {
        if pv.is_null() {
            return STG_E_INVALIDPOINTER;
        }

        let Ok(len) = usize::try_from(cb) else {
            return STG_E_INVALIDPOINTER;
        };

        // SAFETY: The caller provides a buffer valid for writes of `cb` bytes.
        let out = unsafe { core::slice::from_raw_parts_mut(pv.cast::<u8>(), len) };

        trace!(lindex = self.lindex, cb, "Remote file stream read");
        let (count, error) = self.read_into(out);
        // S_FALSE for a read cut short by the end of the file.
        let result = error.unwrap_or(if count < len { S_FALSE } else { S_OK });

        if !pcbread.is_null() {
            // SAFETY: `pcbread` is either null or valid for writes, and `count <= cb`.
            unsafe { pcbread.write(u32::try_from(count).unwrap_or(cb)) };
        }

        result
    }

    fn Write(&self, _pv: *const c_void, _cb: u32, _pcbwritten: *mut u32) -> HRESULT {
        STG_E_ACCESSDENIED
    }
}

impl IStream_Impl for RemoteFileStream_Impl {
    fn Seek(&self, dlibmove: i64, dworigin: STREAM_SEEK, plibnewposition: *mut u64) -> windows::core::Result<()> {
        trace!(
            lindex = self.lindex,
            dlibmove,
            origin = dworigin.0,
            "Remote file stream seek"
        );
        let base = match dworigin {
            STREAM_SEEK_SET => 0,
            STREAM_SEEK_CUR => self.lock_state().position,
            STREAM_SEEK_END => self.size()?,
            _ => return Err(STG_E_INVALIDFUNCTION.into()),
        };

        let position = base.checked_add_signed(dlibmove).ok_or(STG_E_SEEKERROR)?;
        self.lock_state().position = position;

        if !plibnewposition.is_null() {
            // SAFETY: `plibnewposition` is either null or valid for writes.
            unsafe { plibnewposition.write(position) };
        }

        Ok(())
    }

    fn SetSize(&self, _libnewsize: u64) -> windows::core::Result<()> {
        Err(STG_E_ACCESSDENIED.into())
    }

    fn CopyTo(
        &self,
        pstm: Ref<'_, IStream>,
        cb: u64,
        pcbread: *mut u64,
        pcbwritten: *mut u64,
    ) -> windows::core::Result<()> {
        let target = pstm.ok()?;
        let mut buffer = vec![0u8; usize::try_from(MAX_FILE_CONTENTS_CHUNK).unwrap_or(usize::MAX)];
        let mut total_read = 0u64;
        let mut total_written = 0u64;

        let result = loop {
            let wanted = usize::try_from(cb.saturating_sub(total_read))
                .unwrap_or(usize::MAX)
                .min(buffer.len());
            if wanted == 0 {
                break Ok(());
            }

            let (read, error) = self.read_into(&mut buffer[..wanted]);
            if read == 0 {
                break error.map_or(Ok(()), |error| Err(windows::core::Error::from(error)));
            }
            total_read += u64::try_from(read).unwrap_or(u64::MAX);

            if let Err(error) = write_all(target, &buffer[..read], &mut total_written) {
                break Err(error);
            }

            // What was read before a failure is written out first.
            if let Some(error) = error {
                break Err(windows::core::Error::from(error));
            }
        };

        if !pcbread.is_null() {
            // SAFETY: `pcbread` is either null or valid for writes.
            unsafe { pcbread.write(total_read) };
        }
        if !pcbwritten.is_null() {
            // SAFETY: `pcbwritten` is either null or valid for writes.
            unsafe { pcbwritten.write(total_written) };
        }

        result
    }

    fn Commit(&self, _grfcommitflags: &STGC) -> windows::core::Result<()> {
        Ok(())
    }

    fn Revert(&self) -> windows::core::Result<()> {
        Ok(())
    }

    fn LockRegion(&self, _liboffset: u64, _cb: u64, _dwlocktype: &LOCKTYPE) -> windows::core::Result<()> {
        Err(STG_E_INVALIDFUNCTION.into())
    }

    fn UnlockRegion(&self, _liboffset: u64, _cb: u64, _dwlocktype: u32) -> windows::core::Result<()> {
        Err(STG_E_INVALIDFUNCTION.into())
    }

    fn Stat(&self, pstatstg: *mut STATSTG, grfstatflag: &STATFLAG) -> windows::core::Result<()> {
        trace!(lindex = self.lindex, flag = grfstatflag.0, "Remote file stream stat");
        if pstatstg.is_null() {
            return Err(STG_E_INVALIDPOINTER.into());
        }

        let size = self.size()?;
        let descriptor = self.descriptor().ok_or(E_FAIL)?;

        let name = if *grfstatflag == STATFLAG_NONAME {
            PWSTR::null()
        } else {
            co_task_mem_string(&descriptor.name).ok_or(E_OUTOFMEMORY)?
        };

        let mtime = filetime(descriptor.last_write_time.unwrap_or_default());

        // SAFETY: `pstatstg` was checked for null and the caller provides it for writes.
        unsafe {
            pstatstg.write(STATSTG {
                pwcsName: name,
                r#type: STGTY_STREAM.0.cast_unsigned(),
                cbSize: size,
                mtime,
                ctime: mtime,
                atime: mtime,
                grfMode: STGM_READ,
                ..Default::default()
            })
        };

        Ok(())
    }

    fn Clone(&self) -> windows::core::Result<IStream> {
        Err(E_NOTIMPL.into())
    }
}

/// Writes all of `data` to `target`, counting what was written into `total_written`.
///
/// A stream may write less than asked and still succeed: what is left is written again, and a
/// stream that takes nothing is full.
fn write_all(target: &IStream, mut data: &[u8], total_written: &mut u64) -> windows::core::Result<()> {
    while !data.is_empty() {
        let mut written = 0u32;
        let len = u32::try_from(data.len()).unwrap_or(u32::MAX);
        // SAFETY: `data` holds at least `len` initialized bytes.
        let result = unsafe { target.Write(data.as_ptr().cast::<c_void>(), len, Some(&raw mut written)) };
        *total_written += u64::from(written);
        result.ok()?;

        if written == 0 {
            return Err(STG_E_MEDIUMFULL.into());
        }
        data = data
            .get(usize::try_from(written).unwrap_or(usize::MAX)..)
            .unwrap_or(&[]);
    }

    Ok(())
}

fn hglobal_medium(data: &[u8]) -> windows::core::Result<STGMEDIUM> {
    let buffer = GlobalMemoryBuffer::from_slice(data).map_err(|error| match error {
        WinCliprdrError::WinAPI(error) => error,
        _ => E_OUTOFMEMORY.into(),
    })?;

    Ok(STGMEDIUM {
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        u: STGMEDIUM_0 {
            hGlobal: buffer.into_raw(),
        },
        pUnkForRelease: ManuallyDrop::new(None),
    })
}

fn filetime(value: u64) -> FILETIME {
    let [b0, b1, b2, b3, b4, b5, b6, b7] = value.to_le_bytes();

    FILETIME {
        dwLowDateTime: u32::from_le_bytes([b0, b1, b2, b3]),
        dwHighDateTime: u32::from_le_bytes([b4, b5, b6, b7]),
    }
}

/// Copies `value` into a null-terminated UTF-16 string allocated with `CoTaskMemAlloc`, as
/// `STATSTG::pwcsName` requires.
fn co_task_mem_string(value: &str) -> Option<PWSTR> {
    let utf16 = value.encode_utf16().chain(core::iter::once(0)).collect::<Vec<u16>>();
    let byte_len = utf16.len().checked_mul(2)?;

    // SAFETY: Plain allocation; ownership goes to the caller of `Stat`, who frees it.
    let buffer = unsafe { CoTaskMemAlloc(byte_len) }.cast::<u16>();
    if buffer.is_null() {
        return None;
    }

    // SAFETY: `buffer` was just allocated with room for `utf16.len()` code units, and
    // `CoTaskMemAlloc` returns memory suitably aligned for any type.
    unsafe { core::ptr::copy_nonoverlapping(utf16.as_ptr(), buffer, utf16.len()) };

    Some(PWSTR(buffer))
}
