//! OLE data object that puts the remote clipboard on the local one when it holds files.
//!
//! Plain delay rendering (`SetClipboardData(format, NULL)`) can only produce `HGLOBAL`s, but
//! a shell paste needs `CFSTR_FILECONTENTS` as an `IStream` per file (the `lindex`-th entry of
//! `CFSTR_FILEDESCRIPTORW`), so the remote formats are offered through `OleSetClipboard`
//! instead. Each stream reads its file through `FileContentsRequest` `RANGE` requests carrying
//! the `clipDataId` of the lock `Cliprdr` placed on the remote clipboard, so a paste keeps
//! working after the remote clipboard changes, until that lock is released.
//!
//! The objects are not agile: OLE calls them on the thread that called `OleSetClipboard`,
//! which is the thread owning the clipboard window and the [`RemoteTransport`].

#![expect(
    clippy::inline_always,
    clippy::as_pointer_underscore,
    reason = "generated by `#[implement]`"
)]

