/// Bytes fetched ahead when a stream reader asks for less, to save round trips on readers
/// that read in small pieces.
const READ_AHEAD: u32 = 256 * 1024;

const DROPEFFECT_COPY: u32 = 1;

/// Local clipboard format ids (as registered on this machine) used by the data object.
#[derive(Debug, Clone, Copy)]
pub(crate) struct FileFormatIds {
    pub(crate) file_descriptor: u16,
    pub(crate) file_contents: u16,
    pub(crate) preferred_drop_effect: u16,
}

#[implement(IDataObject, Agile = false)]
pub(crate) struct RemoteDataObject {
    transport: Rc<RemoteTransport>,
    generation: u64,
    format_ids: FileFormatIds,
    /// Remote format id of `FileGroupDescriptorW`.
    remote_file_list_format: ClipboardFormatId,
    /// Other remote formats, fetched as `HGLOBAL`s: (local id, remote id).
    passthrough: Vec<(u16, ClipboardFormatId)>,
    formats: Vec<FORMATETC>,
    file_list: RefCell<Option<Rc<RemoteFileList>>>,
}

impl RemoteDataObject {
    pub(crate) fn new(
        transport: Rc<RemoteTransport>,
        format_ids: FileFormatIds,
        remote_file_list_format: ClipboardFormatId,
        passthrough: Vec<(u16, ClipboardFormatId)>,
    ) -> Self {
        let generation = transport.generation();

        let mut formats = vec![
            format_etc(format_ids.file_descriptor, TYMED_HGLOBAL.0),
            format_etc(format_ids.file_contents, TYMED_ISTREAM.0),
            format_etc(format_ids.preferred_drop_effect, TYMED_HGLOBAL.0),
        ];
        formats.extend(
            passthrough
                .iter()
                .map(|(local_format, _)| format_etc(*local_format, TYMED_HGLOBAL.0)),
        );

        Self {
            transport,
            generation,
            format_ids,
            remote_file_list_format,
            passthrough,
            formats,
            file_list: RefCell::new(None),
        }
    }

    fn file_list(&self) -> windows::core::Result<Rc<RemoteFileList>> {
        if let Some(file_list) = self.file_list.borrow().as_ref() {
            return Ok(Rc::clone(file_list));
        }

        if self.transport.generation() != self.generation {
            // The remote clipboard changed before anybody asked for this list.
            return Err(DV_E_FORMATETC.into());
        }

        let file_list = self
            .transport
            .fetch_file_list(self.remote_file_list_format)
            .map_err(|error| {
                warn!(%error, "Failed to get the remote file list");
                windows::core::Error::from(E_FAIL)
            })?;

        debug!(
            file_count = file_list.files.len(),
            clip_data_id = ?file_list.clip_data_id,
            "Received remote file list for paste"
        );

        let file_list = Rc::new(file_list);
        *self.file_list.borrow_mut() = Some(Rc::clone(&file_list));
        Ok(file_list)
    }

    fn file_contents(&self, lindex: i32) -> windows::core::Result<STGMEDIUM> {
        let file_list = self.file_list()?;

        let file_index = usize::try_from(lindex).map_err(|_| DV_E_LINDEX)?;
        let descriptor = file_list.files.get(file_index).ok_or(DV_E_LINDEX)?;
        if is_directory(descriptor) {
            return Err(DV_E_LINDEX.into());
        }

        let stream: IStream = RemoteFileStream {
            transport: Rc::clone(&self.transport),
            file_list: Rc::clone(&file_list),
            lindex,
            state: RefCell::new(StreamState {
                position: 0,
                size: descriptor.file_size,
                buffer: Vec::new(),
                buffer_start: 0,
            }),
        }
        .into();

        Ok(STGMEDIUM {
            tymed: TYMED_ISTREAM.0.cast_unsigned(),
            u: STGMEDIUM_0 {
                pstm: ManuallyDrop::new(Some(stream)),
            },
            pUnkForRelease: ManuallyDrop::new(None),
        })
    }

    fn passthrough_data(&self, remote_format: ClipboardFormatId) -> windows::core::Result<STGMEDIUM> {
        if self.transport.generation() != self.generation {
            return Err(DV_E_FORMATETC.into());
        }

        match self.transport.fetch_format_data(remote_format) {
            Ok(Some(response)) if !response.is_error() => hglobal_medium(response.data()),
            Ok(_) => Err(DV_E_FORMATETC.into()),
            Err(error) => {
                warn!(%error, ?remote_format, "Failed to get remote clipboard data");
                Err(E_FAIL.into())
            }
        }
    }

    /// Validates `format` against what this object offers and returns its `TYMED`.
    fn check_format(&self, format: &FORMATETC) -> Result<u32, HRESULT> {
        // Explorer also asks with other aspects combined (e.g. DVASPECT_CONTENT | DVASPECT_THUMBNAIL).
        if format.dwAspect & DVASPECT_CONTENT.0 == 0 {
            return Err(DV_E_DVASPECT);
        }

        let offered = self
            .formats
            .iter()
            .find(|offered| offered.cfFormat == format.cfFormat)
            .ok_or(DV_E_FORMATETC)?;

        if format.tymed & offered.tymed == 0 {
            return Err(DV_E_TYMED);
        }

        Ok(offered.tymed)
    }
}

impl IDataObject_Impl for RemoteDataObject_Impl {
    fn GetData(&self, pformatetcin: *const FORMATETC) -> windows::core::Result<STGMEDIUM> {
        // SAFETY: OLE passes either null or a pointer valid for the duration of the call.
        let format = unsafe { pformatetcin.as_ref() }.ok_or(E_POINTER)?;
        trace!(
            format = format.cfFormat,
            tymed = format.tymed,
            lindex = format.lindex,
            aspect = format.dwAspect,
            "Clipboard data requested"
        );
        self.check_format(format)?;

        let ids = self.format_ids;

        if format.cfFormat == ids.file_descriptor {
            let file_list = self.file_list()?;
            let data = encode_file_group_descriptor(&file_list.files).ok_or(E_FAIL)?;
            hglobal_medium(&data)
        } else if format.cfFormat == ids.file_contents {
            self.file_contents(format.lindex)
        } else if format.cfFormat == ids.preferred_drop_effect {
            // The remote copy is never moved: nothing here could delete the remote originals.
            hglobal_medium(&DROPEFFECT_COPY.to_le_bytes())
        } else {
            let remote_format = self
                .passthrough
                .iter()
                .find(|(local_format, _)| *local_format == format.cfFormat)
                .map(|(_, remote_format)| *remote_format)
                .ok_or(DV_E_FORMATETC)?;
            self.passthrough_data(remote_format)
        }
    }

    fn GetDataHere(&self, _pformatetc: *const FORMATETC, _pmedium: *mut STGMEDIUM) -> windows::core::Result<()> {
        Err(E_NOTIMPL.into())
    }

    fn QueryGetData(&self, pformatetc: *const FORMATETC) -> HRESULT {
        // SAFETY: OLE passes either null or a pointer valid for the duration of the call.
        let Some(format) = (unsafe { pformatetc.as_ref() }) else {
            return E_POINTER;
        };

        let result = match self.check_format(format) {
            Ok(_) => S_OK,
            Err(error) => error,
        };
        trace!(format = format.cfFormat, tymed = format.tymed, %result, "Clipboard data queried");
        result
    }

    fn GetCanonicalFormatEtc(&self, _pformatectin: *const FORMATETC, pformatetcout: *mut FORMATETC) -> HRESULT {
        // SAFETY: OLE passes either null or a pointer valid for writes for the duration of the call.
        if let Some(format) = unsafe { pformatetcout.as_mut() } {
            format.ptd = core::ptr::null_mut();
        }

        DATA_S_SAMEFORMATETC
    }

    fn SetData(
        &self,
        pformatetc: *const FORMATETC,
        _pmedium: *const STGMEDIUM,
        _frelease: BOOL,
    ) -> windows::core::Result<()> {
        // SAFETY: OLE passes either null or a pointer valid for the duration of the call.
        let format = unsafe { pformatetc.as_ref() }.map(|format| format.cfFormat);
        trace!(?format, "Clipboard data set");
        // Explorer reports "Performed DropEffect" and "Paste Succeeded" here, which only
        // matter for a move.
        Err(E_NOTIMPL.into())
    }

    fn EnumFormatEtc(&self, dwdirection: u32) -> windows::core::Result<IEnumFORMATETC> {
        if dwdirection != DATADIR_GET.0.cast_unsigned() {
            return Err(E_NOTIMPL.into());
        }

        // SAFETY: `formats` is a valid slice of `FORMATETC`s without target devices.
        unsafe { SHCreateStdEnumFmtEtc(&self.formats) }
    }

    fn DAdvise(
        &self,
        _pformatetc: *const FORMATETC,
        _advf: u32,
        _padvsink: Ref<'_, IAdviseSink>,
    ) -> windows::core::Result<u32> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }

    fn DUnadvise(&self, _dwconnection: u32) -> windows::core::Result<()> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }

    fn EnumDAdvise(&self) -> windows::core::Result<IEnumSTATDATA> {
        Err(OLE_E_ADVISENOTSUPPORTED.into())
    }
}

#[derive(Debug)]
struct StreamState {
    position: u64,
    size: Option<u64>,
    /// Bytes received for `buffer_start..buffer_start + buffer.len()`.
    buffer: Vec<u8>,
    buffer_start: u64,
}

impl StreamState {
    fn buffered_at(&self, position: u64) -> &[u8] {
        let Some(offset) = position.checked_sub(self.buffer_start) else {
            return &[];
        };

        usize::try_from(offset)
            .ok()
            .and_then(|offset| self.buffer.get(offset..))
            .unwrap_or(&[])
    }
}

/// Read-only stream over one remote file, `lindex` in the remote file list.
#[implement(IStream, Agile = false)]
struct RemoteFileStream {
    transport: Rc<RemoteTransport>,
    file_list: Rc<RemoteFileList>,
    lindex: i32,
    state: RefCell<StreamState>,
}

impl RemoteFileStream {
    fn descriptor(&self) -> Option<&FileDescriptor> {
        usize::try_from(self.lindex)
            .ok()
            .and_then(|index| self.file_list.files.get(index))
    }

    /// Whether `Cliprdr` still accepts requests against this stream's file list.
    ///
    /// Requests carry the `clipDataId` of the lock taken with the list, which keeps them valid
    /// across remote clipboard changes until `Cliprdr` releases it. Without a lock, they are
    /// checked against the current remote clipboard, so they only make sense until it changes.
    fn can_request(&self) -> bool {
        if self.transport.session() != self.file_list.session {
            return false;
        }

        match self.file_list.clip_data_id {
            Some(clip_data_id) => !self.transport.is_lock_released(clip_data_id),
            None => self.transport.generation() == self.file_list.generation,
        }
    }

    fn request(&self, flags: FileContentsFlags, position: u64, requested_size: u32) -> Result<Vec<u8>, HRESULT> {
        if !self.can_request() {
            debug!(lindex = self.lindex, "Remote file is no longer available");
            return Err(STG_E_READFAULT);
        }

        let huge_file_support = self
            .transport
            .capabilities()
            .contains(ClipboardGeneralCapabilityFlags::HUGE_FILE_SUPPORT_ENABLED);
        if !huge_file_support && HUGE_FILE_POSITION <= position {
            debug!(
                lindex = self.lindex,
                position, "Remote file position needs huge file support"
            );
            return Err(STG_E_READFAULT);
        }

        let request = FileContentsRequest {
            // Assigned by the transport.
            stream_id: 0,
            index: self.lindex,
            flags,
            position,
            requested_size,
            data_id: self.file_list.clip_data_id,
        };

        match self.transport.fetch_file_contents(request) {
            Ok(response) => Ok(response.data().to_vec()),
            Err(error) => {
                warn!(%error, lindex = self.lindex, position, "Failed to read remote file");
                Err(STG_E_READFAULT)
            }
        }
    }

    fn size(&self) -> Result<u64, HRESULT> {
        if let Some(size) = self.state.borrow().size {
            return Ok(size);
        }

        let data = self.request(FileContentsFlags::SIZE, 0, 8)?;
        let size = <[u8; 8]>::try_from(data.as_slice())
            .map(u64::from_le_bytes)
            .map_err(|_| STG_E_READFAULT)?;

        self.state.borrow_mut().size = Some(size);
        Ok(size)
    }

    /// Fills `out` from the current position, returning the byte count; fewer only at the end
    /// of the file or on a failure after some bytes were read.
    fn read_into(&self, out: &mut [u8]) -> Result<usize, HRESULT> {
        let mut filled = 0;

        while let Some(remaining_out) = out.get_mut(filled..).filter(|rest| !rest.is_empty()) {
            let (position, size) = {
                let mut state = self.state.borrow_mut();
                let position = state.position;

                let buffered = state.buffered_at(position);
                if !buffered.is_empty() {
                    let count = buffered.len().min(remaining_out.len());
                    remaining_out[..count].copy_from_slice(&buffered[..count]);
                    filled += count;
                    state.position = position + u64::try_from(count).map_err(|_| STG_E_READFAULT)?;
                    continue;
                }

                (position, state.size)
            };

            let wanted = u32::try_from(remaining_out.len()).unwrap_or(u32::MAX).max(READ_AHEAD);
            let len = range_request_len(position, size, wanted);
            if len == 0 {
                break;
            }

            let data = match self.request(FileContentsFlags::RANGE, position, len) {
                Ok(data) => data,
                Err(error) if filled == 0 => return Err(error),
                Err(_) => break,
            };

            if data.is_empty() {
                // End of a file whose size wasn't advertised.
                break;
            }

            let mut state = self.state.borrow_mut();
            state.buffer = data;
            state.buffer.truncate(usize::try_from(len).unwrap_or(usize::MAX));
            state.buffer_start = position;
        }

        Ok(filled)
    }
}

impl ISequentialStream_Impl for RemoteFileStream_Impl {
    fn Read(&self, pv: *mut c_void, cb: u32, pcbread: *mut u32) -> HRESULT {
        if pv.is_null() {
            return STG_E_INVALIDPOINTER;
        }

        let Ok(len) = usize::try_from(cb) else {
            return STG_E_INVALIDPOINTER;
        };

        // SAFETY: The caller provides a buffer valid for writes of `cb` bytes.
        let out = unsafe { core::slice::from_raw_parts_mut(pv.cast::<u8>(), len) };

        trace!(lindex = self.lindex, cb, "Remote file stream read");
        let (count, result) = match self.read_into(out) {
            Ok(0) if cb != 0 => (0, S_FALSE),
            Ok(count) => (count, S_OK),
            Err(error) => (0, error),
        };

        if !pcbread.is_null() {
            // SAFETY: `pcbread` is either null or valid for writes, and `count <= cb`.
            unsafe { pcbread.write(u32::try_from(count).unwrap_or(cb)) };
        }

        result
    }

    fn Write(&self, _pv: *const c_void, _cb: u32, _pcbwritten: *mut u32) -> HRESULT {
        STG_E_ACCESSDENIED
    }
}

impl IStream_Impl for RemoteFileStream_Impl {
    fn Seek(&self, dlibmove: i64, dworigin: STREAM_SEEK, plibnewposition: *mut u64) -> windows::core::Result<()> {
        trace!(
            lindex = self.lindex,
            dlibmove,
            origin = dworigin.0,
            "Remote file stream seek"
        );
        let base = match dworigin {
            STREAM_SEEK_SET => 0,
            STREAM_SEEK_CUR => self.state.borrow().position,
            STREAM_SEEK_END => self.size()?,
            _ => return Err(STG_E_INVALIDFUNCTION.into()),
        };

        let position = base.checked_add_signed(dlibmove).ok_or(STG_E_SEEKERROR)?;
        self.state.borrow_mut().position = position;

        if !plibnewposition.is_null() {
            // SAFETY: `plibnewposition` is either null or valid for writes.
            unsafe { plibnewposition.write(position) };
        }

        Ok(())
    }

    fn SetSize(&self, _libnewsize: u64) -> windows::core::Result<()> {
        Err(STG_E_ACCESSDENIED.into())
    }

    fn CopyTo(
        &self,
        pstm: Ref<'_, IStream>,
        cb: u64,
        pcbread: *mut u64,
        pcbwritten: *mut u64,
    ) -> windows::core::Result<()> {
        let target = pstm.ok()?;
        let mut buffer = vec![0u8; usize::try_from(MAX_FILE_CONTENTS_CHUNK).unwrap_or(usize::MAX)];
        let mut total_read = 0u64;
        let mut total_written = 0u64;

        let result = loop {
            let wanted = usize::try_from(cb.saturating_sub(total_read))
                .unwrap_or(usize::MAX)
                .min(buffer.len());
            if wanted == 0 {
                break Ok(());
            }

            let read = match self.read_into(&mut buffer[..wanted]) {
                Ok(0) => break Ok(()),
                Ok(read) => read,
                Err(error) => break Err(windows::core::Error::from(error)),
            };
            total_read += u64::try_from(read).unwrap_or(u64::MAX);

            let mut written = 0u32;
            let read = u32::try_from(read).unwrap_or(u32::MAX);
            // SAFETY: `buffer` holds `read` initialized bytes.
            let write_result = unsafe { target.Write(buffer.as_ptr().cast::<c_void>(), read, Some(&raw mut written)) };
            total_written += u64::from(written);
            if let Err(error) = write_result.ok() {
                break Err(error);
            }
        };

        if !pcbread.is_null() {
            // SAFETY: `pcbread` is either null or valid for writes.
            unsafe { pcbread.write(total_read) };
        }
        if !pcbwritten.is_null() {
            // SAFETY: `pcbwritten` is either null or valid for writes.
            unsafe { pcbwritten.write(total_written) };
        }

        result
    }

    fn Commit(&self, _grfcommitflags: &STGC) -> windows::core::Result<()> {
        Ok(())
    }

    fn Revert(&self) -> windows::core::Result<()> {
        Ok(())
    }

    fn LockRegion(&self, _liboffset: u64, _cb: u64, _dwlocktype: &LOCKTYPE) -> windows::core::Result<()> {
        Err(STG_E_INVALIDFUNCTION.into())
    }

    fn UnlockRegion(&self, _liboffset: u64, _cb: u64, _dwlocktype: u32) -> windows::core::Result<()> {
        Err(STG_E_INVALIDFUNCTION.into())
    }

    fn Stat(&self, pstatstg: *mut STATSTG, grfstatflag: &STATFLAG) -> windows::core::Result<()> {
        trace!(lindex = self.lindex, flag = grfstatflag.0, "Remote file stream stat");
        if pstatstg.is_null() {
            return Err(STG_E_INVALIDPOINTER.into());
        }

        let size = self.size()?;
        let descriptor = self.descriptor().ok_or(E_FAIL)?;

        let name = if *grfstatflag == STATFLAG_NONAME {
            PWSTR::null()
        } else {
            co_task_mem_string(&descriptor.name).ok_or(E_OUTOFMEMORY)?
        };

        let mtime = filetime(descriptor.last_write_time.unwrap_or_default());

        // SAFETY: `pstatstg` was checked for null and the caller provides it for writes.
        unsafe {
            pstatstg.write(STATSTG {
                pwcsName: name,
                r#type: STGTY_STREAM.0.cast_unsigned(),
                cbSize: size,
                mtime,
                ctime: mtime,
                atime: mtime,
                grfMode: STGM_READ,
                ..Default::default()
            })
        };

        Ok(())
    }

    fn Clone(&self) -> windows::core::Result<IStream> {
        Err(E_NOTIMPL.into())
    }
}

fn format_etc(format: u16, tymed: i32) -> FORMATETC {
    FORMATETC {
        cfFormat: format,
        ptd: core::ptr::null_mut(),
        dwAspect: DVASPECT_CONTENT.0,
        lindex: -1,
        tymed: tymed.cast_unsigned(),
    }
}

fn hglobal_medium(data: &[u8]) -> windows::core::Result<STGMEDIUM> {
    let buffer = GlobalMemoryBuffer::from_slice(data).map_err(|error| match error {
        WinCliprdrError::WinAPI(error) => error,
        _ => E_OUTOFMEMORY.into(),
    })?;

    Ok(STGMEDIUM {
        tymed: TYMED_HGLOBAL.0.cast_unsigned(),
        u: STGMEDIUM_0 {
            hGlobal: buffer.into_raw(),
        },
        pUnkForRelease: ManuallyDrop::new(None),
    })
}

fn filetime(value: u64) -> FILETIME {
    let [b0, b1, b2, b3, b4, b5, b6, b7] = value.to_le_bytes();

    FILETIME {
        dwLowDateTime: u32::from_le_bytes([b0, b1, b2, b3]),
        dwHighDateTime: u32::from_le_bytes([b4, b5, b6, b7]),
    }
}

/// Copies `value` into a null-terminated UTF-16 string allocated with `CoTaskMemAlloc`, as
/// `STATSTG::pwcsName` requires.
fn co_task_mem_string(value: &str) -> Option<PWSTR> {
    let utf16 = value.encode_utf16().chain(core::iter::once(0)).collect::<Vec<u16>>();
    let byte_len = utf16.len().checked_mul(2)?;

    // SAFETY: Plain allocation; ownership goes to the caller of `Stat`, who frees it.
    let buffer = unsafe { CoTaskMemAlloc(byte_len) }.cast::<u16>();
    if buffer.is_null() {
        return None;
    }

    // SAFETY: `buffer` was just allocated with room for `utf16.len()` code units, and
    // `CoTaskMemAlloc` returns memory suitably aligned for any type.
    unsafe { core::ptr::copy_nonoverlapping(utf16.as_ptr(), buffer, utf16.len()) };

    Some(PWSTR(buffer))
}
