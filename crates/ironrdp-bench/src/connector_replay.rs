use sha2::{Digest as _, Sha256};

const MAX_CONNECTOR_STEPS: usize = 128;

/// Expected result of one connection driven from a capture, stored as `[capture.connector]` in the manifest.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct ConnectorExpectation {
    /// Connector `step` and `step_no_input` calls up to `Connected`.
    pub steps: usize,
    /// Complete frames written by the connector.
    pub outbound_frames: usize,
    /// Decrypted server frames consumed by the connector.
    pub server_frames: usize,
    /// SHA-256 of every byte written by the connector, with Channel Join Requests sorted.
    pub fingerprint: String,
}

/// Payload-free observations from one connection.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ConnectorMeasurement {
    /// Connector `step` and `step_no_input` calls up to `Connected`.
    pub steps: usize,
    /// Decrypted server frames consumed by the connector.
    pub server_frames: usize,
    /// Bytes written by the connector.
    pub outbound_bytes: usize,
}

/// One capture prepared for repeated connections.
pub struct ConnectorReplay {
    expected: ConnectorExpectation,
    config: Config,
    client_addr: SocketAddr,
    channels: Vec<ChannelDef>,
    server_confirm: Vec<u8>,
    server_frames: Vec<Vec<u8>>,
}

impl ConnectorReplay {
    /// Read and decrypt a verified capture, and derive the client configuration from its client frames.
    pub(crate) fn prepare(capture_path: &Path, expected: ConnectorExpectation) -> anyhow::Result<Self> {
        let capture = read_capture(capture_path).with_context(|| format!("read capture {}", capture_path.display()))?;
        let client_request = first_frame(&capture.flow.client_stream).context("captured Connection Request")?;
        let server_confirm = first_frame(&capture.flow.server_stream).context("captured Connection Confirm")?;
        let request = decode::<X224<nego::ConnectionRequest>>(&client_request)
            .map_err(|error| anyhow!("decode captured Connection Request: {error}"))?
            .0;
        let confirm = decode::<X224<nego::ConnectionConfirm>>(&server_confirm)
            .map_err(|error| anyhow!("decode captured Connection Confirm: {error}"))?
            .0;
        ensure!(
            request.protocol == nego::SecurityProtocol::SSL
                && matches!(
                    confirm,
                    nego::ConnectionConfirm::Response {
                        protocol: nego::SecurityProtocol::SSL,
                        ..
                    }
                ),
            "connector benchmark requires a TLS-only negotiation"
        );

        let plaintext = decrypt_tls(&capture).context("decrypt capture")?;
        let client_bytes = concat(&plaintext.client);
        let (config, client_addr, channels) = captured_config(request, &split_frames(&client_bytes)?)?;
        Ok(Self {
            expected,
            config,
            client_addr,
            channels,
            server_confirm,
            server_frames: split_frames(&concat(&plaintext.server))?
                .into_iter()
                .map(<[u8]>::to_vec)
                .collect(),
        })
    }

    /// Construct a fresh connector and step it to `Connected` from the captured server frames.
    pub fn replay(&self) -> anyhow::Result<ConnectorMeasurement> {
        self.drive().map(|(measurement, _)| measurement)
    }

    /// Run one fresh connection and compare everything it wrote with the expectation.
    pub fn verify(&self) -> anyhow::Result<ConnectorMeasurement> {
        let (measurement, observed, pdus) = self.observe()?;
        ensure!(observed == self.expected, "{}", mismatch(&observed, &pdus)?);
        Ok(measurement)
    }

    /// Whether `replay` consumed and produced what the expectation records, without hashing its output.
    pub fn matches_counts(&self, measurement: &ConnectorMeasurement) -> bool {
        measurement.steps == self.expected.steps && measurement.server_frames == self.expected.server_frames
    }

    /// Run one fresh connection and describe it, with outbound PDU names for diagnostics.
    pub(crate) fn observe(&self) -> anyhow::Result<(ConnectorMeasurement, ConnectorExpectation, Vec<&'static str>)> {
        let (measurement, output) = self.drive()?;
        let frames = split_frames(output.filled())?;
        let pdus = frames
            .iter()
            .map(|frame| outbound_pdu(frame))
            .collect::<anyhow::Result<Vec<_>>>()?;
        // ironrdp-connector channel_connection.rs joins channels in `HashSet` order, so pin the set, not the order.
        let mut ordered = frames.clone();
        let is_join = |pdu: &&str| *pdu == "ChannelJoinRequest";
        if let (Some(first), Some(last)) = (pdus.iter().position(is_join), pdus.iter().rposition(is_join)) {
            ensure!(
                pdus[first..=last].iter().all(is_join),
                "Channel Join Requests are not contiguous: {pdus:?}"
            );
            ordered[first..=last].sort_unstable();
        }
        let mut fingerprint = Sha256::new();
        for frame in ordered {
            fingerprint.update(frame);
        }
        let observed = ConnectorExpectation {
            steps: measurement.steps,
            outbound_frames: frames.len(),
            server_frames: measurement.server_frames,
            fingerprint: format!("{:x}", fingerprint.finalize()),
        };
        Ok((measurement, observed, pdus))
    }

    fn drive(&self) -> anyhow::Result<(ConnectorMeasurement, WriteBuf)> {
        let mut connector = ClientConnector::new(self.config.clone(), self.client_addr);
        for channel in &self.channels {
            ensure!(
                connector.attach_dynamic_static_channel(OpaqueChannel(channel.clone())),
                "connector rejected a captured static channel"
            );
        }

        let mut output = WriteBuf::new();
        connector
            .step_no_input(&mut output)
            .map_err(|error| anyhow!("send Connection Request: {error}"))?;
        connector
            .step(&self.server_confirm, None, &mut output)
            .map_err(|error| anyhow!("receive Connection Confirm: {error}"))?;
        ensure!(
            connector.should_perform_security_upgrade(),
            "connector did not stop at the TLS boundary"
        );
        connector.mark_security_upgrade_as_done();

        let mut steps = 2;
        let mut server_frames = self.server_frames.iter();
        while !matches!(connector.state, ClientConnectorState::Connected { .. }) {
            ensure!(
                steps < MAX_CONNECTOR_STEPS,
                "connector exceeded {MAX_CONNECTOR_STEPS} steps"
            );
            ensure!(!connector.should_perform_credssp(), "no-NLA connection reached CredSSP");
            ensure!(
                !connector.should_perform_multitransport(),
                "connection reached a multitransport handoff"
            );
            let result = if connector.next_pdu_hint().is_some() {
                let frame = server_frames
                    .next()
                    .with_context(|| format!("server frames ended in {}", connector.state().name()))?;
                connector.step(frame, None, &mut output)
            } else {
                connector.step_no_input(&mut output)
            };
            result.map_err(|error| anyhow!("connector step {steps}: {error}"))?;
            steps += 1;
        }

        let measurement = ConnectorMeasurement {
            steps,
            server_frames: self.server_frames.len() - server_frames.len(),
            outbound_bytes: output.filled_len(),
        };
        Ok((measurement, output))
    }
}

/// Describe an observed connection as a paste-ready manifest table, followed by its outbound PDU names.
pub(crate) fn mismatch(observed: &ConnectorExpectation, pdus: &[&str]) -> anyhow::Result<String> {
    Ok(format!(
        "connector result does not match its expectation; replace it with:\n[capture.connector]\n{}outbound PDUs: {pdus:?}",
        toml::to_string(observed)?
    ))
}

/// A captured static channel that is joined but never processes payloads before `Connected`.
#[derive(Debug)]
struct OpaqueChannel(ChannelDef);

impl_as_any!(OpaqueChannel);

impl SvcProcessor for OpaqueChannel {
    fn channel_name(&self) -> gcc::ChannelName {
        self.0.name.clone()
    }

    fn channel_options(&self) -> ChannelOptions {
        self.0.options
    }

    fn process(&mut self, _payload: &[u8]) -> ironrdp::pdu::PduResult<Vec<SvcMessage>> {
        Ok(Vec::new())
    }
}

impl SvcClientProcessor for OpaqueChannel {}

fn captured_config(
    request: nego::ConnectionRequest,
    client_frames: &[&[u8]],
) -> anyhow::Result<(Config, SocketAddr, Vec<ChannelDef>)> {
    let initial = client_frames
        .iter()
        .find_map(|frame| {
            let payload = decode::<X224<X224Data<'_>>>(frame).ok()?.0;
            decode::<mcs::ConnectInitial>(payload.data.as_ref()).ok()
        })
        .context("client frames have no MCS Connect Initial")?;
    let user_data = client_frames
        .iter()
        .filter_map(|frame| match decode::<X224<mcs::McsMessage<'_>>>(frame).ok()?.0 {
            mcs::McsMessage::SendDataRequest(data) => Some(data.user_data.into_owned()),
            _ => None,
        })
        .collect::<Vec<_>>();
    let client_info = user_data
        .iter()
        .find_map(|data| decode::<ClientInfoPdu>(data).ok())
        .context("client frames have no Client Info")?
        .client_info;
    let platform = user_data
        .iter()
        .find_map(
            |data| match decode::<ShareControlHeader>(data).ok()?.share_control_pdu {
                ShareControlPdu::ClientConfirmActive(confirm) => {
                    confirm.pdu.capability_sets.into_iter().find_map(|set| match set {
                        CapabilitySet::General(general) => Some(general.major_platform_type),
                        _ => None,
                    })
                }
                _ => None,
            },
        )
        .context("client frames have no Confirm Active General capability set")?;

    let blocks = initial.conference_create_request.gcc_blocks();
    let core = &blocks.core;
    let optional = &core.optional_data;
    let extra = &client_info.extra_info;
    let flags = client_info.flags;
    let address = extra
        .address
        .parse::<IpAddr>()
        .with_context(|| format!("captured client address is not an IP address: {}", extra.address))?;
    let config = Config {
        desktop_size: DesktopSize {
            width: core.desktop_width,
            height: core.desktop_height,
        },
        monitor_layout: blocks.monitor.clone(),
        desktop_scale_factor: optional.desktop_scale_factor.unwrap_or_default(),
        enable_tls: true,
        enable_credssp: false,
        enable_standard_rdp_security: false,
        credentials: Credentials::UsernamePassword {
            username: String::new(),
            password: String::new(),
        },
        domain: None,
        client_build: core.client_build,
        client_name: core.client_name.clone(),
        keyboard_type: core.keyboard_type,
        keyboard_subtype: core.keyboard_subtype,
        keyboard_functional_keys_count: core.keyboard_functional_keys_count,
        keyboard_layout: core.keyboard_layout,
        connection_type: optional.connection_type.unwrap_or(gcc::ConnectionType::Lan),
        ime_file_name: core.ime_file_name.clone(),
        bitmap: None,
        dig_product_id: optional.dig_product_id.clone().unwrap_or_default(),
        client_dir: extra.dir.clone(),
        alternate_shell: client_info.alternate_shell.clone(),
        work_dir: client_info.work_dir.clone(),
        remote_application_mode: flags.contains(ClientInfoFlags::RAIL),
        rail_support_level: RailSupportLevel::SUPPORTED,
        platform,
        hardware_id: None,
        request_data: request.nego_data,
        autologon: flags.contains(ClientInfoFlags::AUTOLOGON),
        enable_audio_playback: !flags.contains(ClientInfoFlags::NO_AUDIO_PLAYBACK),
        enable_audio_capture: flags.contains(ClientInfoFlags::AUDIO_CAPTURE),
        performance_flags: extra.optional_data.performance_flags().unwrap_or_default(),
        license_cache: None,
        timezone_info: extra.optional_data.timezone().cloned().unwrap_or_default(),
        compression_type: flags
            .contains(ClientInfoFlags::COMPRESSION)
            .then_some(client_info.compression_type),
        enable_server_pointer: false,
        pointer_software_rendering: false,
        multitransport_flags: blocks.multi_transport_channel.as_ref().map(|data| data.flags),
        support_dyn_vc_gfx_protocol: optional
            .early_capability_flags
            .is_some_and(|flags| flags.contains(ClientEarlyCapabilityFlags::SUPPORT_DYN_VC_GFX_PROTOCOL)),
    };
    let channels = blocks
        .network
        .as_ref()
        .map(|network| network.channels.clone())
        .unwrap_or_default();
    Ok((config, SocketAddr::new(address, 0), channels))
}

/// Name one outbound frame for mismatch diagnostics, failing closed on licensing output.
fn outbound_pdu(frame: &[u8]) -> anyhow::Result<&'static str> {
    if decode::<X224<nego::ConnectionRequest>>(frame).is_ok() {
        return Ok("ConnectionRequest");
    }
    let Ok(message) = decode::<X224<mcs::McsMessage<'_>>>(frame) else {
        let is_connect_initial = decode::<X224<X224Data<'_>>>(frame)
            .is_ok_and(|payload| decode::<mcs::ConnectInitial>(payload.0.data.as_ref()).is_ok());
        return Ok(if is_connect_initial {
            "ConnectInitial"
        } else {
            "Unknown"
        });
    };
    match message.0 {
        mcs::McsMessage::ErectDomainRequest(_) => Ok("ErectDomainRequest"),
        mcs::McsMessage::AttachUserRequest(_) => Ok("AttachUserRequest"),
        mcs::McsMessage::ChannelJoinRequest(_) => Ok("ChannelJoinRequest"),
        mcs::McsMessage::SendDataRequest(data) if decode::<ClientInfoPdu>(data.user_data.as_ref()).is_ok() => {
            Ok("ClientInfo")
        }
        mcs::McsMessage::SendDataRequest(data) if decode::<LicensePdu>(data.user_data.as_ref()).is_ok() => {
            Err(anyhow!("connector sent a licensing PDU"))
        }
        mcs::McsMessage::SendDataRequest(_) => Ok("SendData"),
        _ => Ok("OtherMcs"),
    }
}

fn first_frame(stream: &PacketStream) -> anyhow::Result<Vec<u8>> {
    let bytes = concat(stream);
    let info = find_size(&bytes)
        .map_err(|error| anyhow!("frame: {error}"))?
        .context("truncated frame")?;
    ensure!(
        info.action == Action::X224 && info.length <= bytes.len(),
        "invalid initial frame"
    );
    Ok(bytes[..info.length].to_vec())
}

fn concat(stream: &PacketStream) -> Vec<u8> {
    stream.iter().flat_map(|(_, bytes)| bytes).copied().collect()
}

fn split_frames(bytes: &[u8]) -> anyhow::Result<Vec<&[u8]>> {
    let mut frames = Vec::new();
    let mut rest = bytes;
    while !rest.is_empty() {
        let info = find_size(rest)
            .map_err(|error| anyhow!("frame: {error}"))?
            .context("truncated frame")?;
        ensure!(info.length <= rest.len(), "truncated frame");
        let (frame, tail) = rest.split_at(info.length);
        frames.push(frame);
        rest = tail;
    }
    ensure!(!frames.is_empty(), "stream has no frames");
    Ok(frames)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_empty_and_truncated_streams() {
        assert!(split_frames(&[]).is_err());
        assert!(split_frames(&[0x03, 0x00, 0x00, 0x06]).is_err());
    }

    #[test]
    fn reports_mismatch_as_manifest_table() {
        let observed = ConnectorExpectation {
            steps: 2,
            outbound_frames: 1,
            server_frames: 1,
            fingerprint: "ab".to_owned(),
        };
        let report = mismatch(&observed, &["ConnectionRequest"]).expect("expectation must serialize");
        let table = report
            .split_once("[capture.connector]\n")
            .and_then(|(_, rest)| rest.split_once("outbound PDUs"))
            .expect("report must contain the manifest table")
            .0;
        assert_eq!(
            toml::from_str::<ConnectorExpectation>(table).expect("table must parse"),
            observed
        );
    }
}
