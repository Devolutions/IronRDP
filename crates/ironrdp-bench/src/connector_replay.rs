//! Capture-backed connection benchmark for the production `ClientConnector`.
//!
//! Each run constructs the connector, attaches the captured static channels, and steps it to `Connected`.
//! The captured X.224 Connection Confirm and decrypted server frames are its only input; captured client frames only supply its configuration.
//! The session that follows `Connected` is measured by the capture replay, not here.
//!
//! Known divergences from the captured client:
//! - The TLS handshake is not run: the connector is marked upgraded at the captured TLS boundary, and CredSSP fails the run.
//! - Credentials are empty so no captured secret is replayed.
//! - Client Info flags other than compression, audio, autologon, and RAIL are the connector's own.
//! - Confirm Active capability sets are generated by the connector, not copied from the capture.
//! - GCC cluster data is not sent.
//! - Static channels are opaque and never receive payloads before `Connected`.

